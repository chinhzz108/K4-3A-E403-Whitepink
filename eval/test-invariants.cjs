const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename,'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,filename);
const {reconcileEvidence,usableFacts,validateSentences,quoteMatches} = require('../codebase/lib/evidence.ts');
const {scrapePage} = require('../codebase/lib/scraper.ts');
(async()=>{
  assert.equal(quoteMatches('A completely fabricated quotation.', 'This page contains other text.'),false);
  const page={url:'https://example.org/article',title:'Title',content:'This is an exact evidence quotation for testing.',status:'ok',fetchedAt:new Date().toISOString(),promptInjectionDetected:false};
  const source={id:'n01',url:page.url,trangThai:'dang-dung',doanTrich:page.content,tacGia:'invented',ngayDang:'2099-01-01'};
  const fact={id:'t01',bangChung:[{nguonId:'n01',doanTrich:page.content}],trangThai:'da-xac-minh'};
  const checked=reconcileEvidence([source],[fact],[page]);
  assert.equal(checked.sources[0].tacGia,undefined);
  assert.equal(checked.sources[0].ngayDang,undefined);
  assert.equal(checked.facts[0].trangThai,'chua-xac-minh');
  assert.equal(reconcileEvidence([source],[fact],[{...page,promptInjectionDetected:true}]).sources[0].trangThai,'bi-loai');
  assert.equal(usableFacts([fact],[{...source,trangThai:'bi-loai'}]).length,0);
  assert.throws(()=>validateSentences([{n:1,loi:'Claim',chuTrenManHinh:'Claim',yDoHinh:'Image',nguon:['unknown']}],[fact],1));
  const injection=await scrapePage('http://localhost:3000/fixtures/prompt-injection.html');
  assert.equal(injection.promptInjectionDetected,true);
  const blocked=await scrapePage('http://localhost:3000/fixtures/unreadable.html');
  assert.equal(blocked.status,'blocked');
  const missing=await scrapePage('http://localhost:3000/fixtures/missing.html');
  assert.equal(missing.status,'not-found');
  const fake=await scrapePage('https://source.test/article');
  assert.equal(fake.status,'error');
  const result={testedAt:new Date().toISOString(),assertions:11,pass:11,note:'Technical invariants only, not 11 additional golden cases',injection,blocked,missing,fake};
  fs.writeFileSync(process.env.INVARIANT_REPORT || 'eval/cp3/invariants-latest.json',JSON.stringify(result,null,2));
  console.log('11/11 technical invariants passed');
})();
